#!/usr/bin/env node
// Copies the pure engine (src/engine/*.ts, excluding tests) into the Supabase Edge Function
// shared folder so Deno can import it. Run with `npm run engine:sync`.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const HEADER = '// GENERATED by npm run engine:sync – do not edit\n';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SRC_DIR = join(root, 'src', 'engine');
export const DEST_DIR = join(root, 'supabase', 'functions', '_shared', 'engine');

/** Engine source files that belong in the copy (no tests or test helpers). */
export function engineFiles(dir = SRC_DIR) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && !/\.test(-utils)?\.ts$/.test(f) && !f.endsWith('.d.ts'))
    .sort();
}

export function sync() {
  mkdirSync(DEST_DIR, { recursive: true });
  const files = engineFiles();
  const keep = new Set(files);
  for (const f of readdirSync(DEST_DIR)) {
    if (!keep.has(f)) rmSync(join(DEST_DIR, f), { recursive: true, force: true });
  }
  for (const f of files) {
    writeFileSync(join(DEST_DIR, f), HEADER + readFileSync(join(SRC_DIR, f), 'utf8'));
  }
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = sync();
  console.log(`engine:sync – copied ${files.length} files to ${DEST_DIR}`);
}
